const LANGUAGE_STORAGE_KEY = "portfolioLangV3";
const DEFAULT_LANGUAGE = "en";
const menuButton = document.querySelector(".menu-button");
const menuPanel = document.querySelector(".menu-panel");
const menuClose = document.querySelector(".menu-close");
const languageButtons = document.querySelectorAll("[data-lang]");
const translatable = document.querySelectorAll("[data-i18n]");
const page = document.body.dataset.page;

function readStoredLang() {
  try {
    const storedLang = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return translations[storedLang] ? storedLang : DEFAULT_LANGUAGE;
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

function writeStoredLang(lang) {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
  } catch {
    // Some file:// browser contexts block storage; language still works for this page load.
  }
}

let currentLang = readStoredLang();
let currentProjectIndex = 0;

function setMenu(open) {
  document.body.classList.toggle("menu-is-open", open);
  menuPanel?.classList.toggle("menu-open", open);
  menuPanel?.setAttribute("aria-hidden", String(!open));
  menuButton?.setAttribute("aria-expanded", String(open));
}

function applyLanguage(lang) {
  currentLang = translations[lang] ? lang : DEFAULT_LANGUAGE;
  writeStoredLang(currentLang);
  document.documentElement.lang = currentLang === "zh" ? "zh-CN" : "en";

  translatable.forEach((element) => {
    const key = element.dataset.i18n;
    const value = translations[currentLang][key];
    if (value !== undefined) element.textContent = value;
  });

  languageButtons.forEach((button) => {
    button.classList.toggle("active-lang", button.dataset.lang === currentLang);
  });

  if (document.querySelector(".project-dialog")?.open) {
    renderProject(currentProjectIndex);
  }
}

function markCurrentPage() {
  document.querySelectorAll(".header-nav a, .menu-links a").forEach((link) => {
    const target = link.getAttribute("href")?.replace(".html", "") || "index";
    const normalizedPage = page === "home" ? "index" : page;
    link.classList.toggle("active-page", target === normalizedPage);
  });
}

menuButton?.addEventListener("click", () => setMenu(true));
menuClose?.addEventListener("click", () => setMenu(false));
document.querySelector(".header-actions")?.addEventListener("click", (event) => {
  const languageButton = event.target.closest("[data-lang]");
  if (languageButton) applyLanguage(languageButton.dataset.lang);
});
menuPanel?.addEventListener("click", (event) => {
  const languageButton = event.target.closest("[data-lang]");
  if (languageButton) {
    applyLanguage(languageButton.dataset.lang);
    return;
  }

  if (event.target === menuPanel) setMenu(false);
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") setMenu(false);
});

const homeAboutSection = document.querySelector(".home-about");

if (page === "home" && homeAboutSection && "IntersectionObserver" in window) {
  const homePhotoObserver = new IntersectionObserver(
    ([entry]) => {
      document.body.classList.toggle("home-about-active", entry.isIntersecting);
    },
    {
      rootMargin: "-24% 0px -38%",
      threshold: 0,
    }
  );

  homePhotoObserver.observe(homeAboutSection);
}

const aboutImageSections = document.querySelectorAll("[data-about-image]");
const aboutScrollPhoto = document.querySelector(".about-scroll-photo");
const aboutScrollImage = document.querySelector(".about-scroll-image");

if (page === "about" && aboutImageSections.length && aboutScrollImage && "IntersectionObserver" in window) {
  let activeAboutImage = aboutScrollImage.getAttribute("src");
  let aboutImageTimer;

  function setAboutImage(section) {
    const nextImage = section.dataset.aboutImage;
    if (!nextImage || nextImage === activeAboutImage) return;

    window.clearTimeout(aboutImageTimer);
    aboutScrollPhoto?.classList.add("is-switching");

    aboutImageTimer = window.setTimeout(() => {
      activeAboutImage = nextImage;
      aboutScrollImage.src = nextImage;
      aboutScrollImage.alt = section.dataset.aboutAlt || "";
      aboutScrollPhoto?.classList.remove("is-switching");
    }, 180);
  }

  const aboutSectionObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;

        aboutImageSections.forEach((section) => {
          section.classList.toggle("is-active", section === entry.target);
        });
        setAboutImage(entry.target);
      });
    },
    {
      rootMargin: "-32% 0px -42%",
      threshold: 0,
    }
  );

  aboutImageSections.forEach((section) => aboutSectionObserver.observe(section));
}

const dialog = document.querySelector(".project-dialog");
const dialogImage = document.querySelector(".dialog-image");
const dialogTitle = document.querySelector(".dialog-title");
const dialogText = document.querySelector(".dialog-text");
const dialogTags = document.querySelector(".dialog-tags");
const dialogClose = document.querySelector(".dialog-close");
const dialogPrev = document.querySelector(".dialog-prev");
const dialogNext = document.querySelector(".dialog-next");

function renderProject(index) {
  const project = projectData[index];
  if (!project || !dialogImage || !dialogTitle || !dialogText || !dialogTags) return;

  dialogImage.src = project.image;
  dialogImage.alt = `${project.title.en} preview`;
  dialogTitle.textContent = project.title[currentLang];
  dialogText.textContent = project.text[currentLang];
  dialogTags.innerHTML = "";

  project.tags.forEach((tag) => {
    const pill = document.createElement("span");
    pill.textContent = tag;
    dialogTags.appendChild(pill);
  });
}

function openProject(index) {
  if (!dialog) return;
  currentProjectIndex = index;
  renderProject(currentProjectIndex);
  dialog.showModal();
}

function shiftProject(direction) {
  currentProjectIndex = (currentProjectIndex + direction + projectData.length) % projectData.length;
  renderProject(currentProjectIndex);
}

document.querySelectorAll("[data-project-index]").forEach((card) => {
  card.addEventListener("click", () => openProject(Number(card.dataset.projectIndex)));
});

dialogClose?.addEventListener("click", () => dialog?.close());
dialogPrev?.addEventListener("click", () => shiftProject(-1));
dialogNext?.addEventListener("click", () => shiftProject(1));

dialog?.addEventListener("keydown", (event) => {
  if (event.key === "ArrowLeft") shiftProject(-1);
  if (event.key === "ArrowRight") shiftProject(1);
});

markCurrentPage();
applyLanguage(currentLang);
